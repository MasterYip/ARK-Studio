"""Server JSON config keys and environment variables: where Python and Go read them.

    python -B tests/python/contract/config_parity.py           # rewrite config-parity.md
    python -B tests/python/contract/config_parity.py --check   # fail if stale or a name is unread in Go

For every config key and environment variable of contract.json this lists the
Python modules that read it (from the contract) and the Go files that name it
as a string literal.  A name with no Go reader fails the check unless it is in
GO_NOT_NEEDED with a reason.  Behaviour is compared by the differential
replay, cli_diff.py (serve-config-* cases) and the Go unit tests; this table
is the inventory that nothing was forgotten.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
CONTRACT = REPO / "docs" / "development" / "go-port" / "contract.json"
OUT = REPO / "docs" / "development" / "go-port" / "config-parity.md"

# Names Go deliberately does not read (none at the moment).
GO_NOT_NEEDED: dict[str, str] = {}


def go_sources() -> dict[str, str]:
    out = {}
    for path in sorted((REPO / "go").rglob("*.go")):
        if path.name.endswith("_test.go"):
            continue
        out[path.relative_to(REPO).as_posix()] = path.read_text(encoding="utf-8", errors="replace")
    return out


def readers(name: str, sources: dict[str, str]) -> list[str]:
    pattern = re.compile(r'["`]' + re.escape(name) + r'["`=]')
    return [path for path, text in sources.items() if pattern.search(text)]


def render() -> tuple[str, list[str]]:
    contract = json.loads(CONTRACT.read_text(encoding="utf-8"))
    sources = go_sources()
    missing: list[str] = []
    lines = ["# Config keys and environment variables (Python vs Go)", "",
             "Generated by `tests/python/contract/config_parity.py`; checked by "
             "`test_contract_inventory.py`. Go readers are files naming the key as a string literal.", "",
             f"## Server JSON config keys ({len(contract['config_keys'])})", "",
             "| key | type | env fallback | Go readers |", "|---|---|---|---|"]
    for item in contract["config_keys"]:
        found = readers(item["key"], sources)
        if not found and item["key"] not in GO_NOT_NEEDED:
            missing.append(item["key"])
        go = ", ".join(f"`{p.removeprefix('go/')}`" for p in found) or GO_NOT_NEEDED.get(item["key"], "**missing**")
        lines.append(f"| `{item['key']}` | {item['type']} | {item.get('env') or '-'} | {go} |")
    lines += ["", f"## Environment variables ({len(contract['env_vars'])})", "",
              "| variable | Python readers | Go readers |", "|---|---|---|"]
    for name, py in sorted(contract["env_vars"].items()):
        found = readers(name, sources)
        if not found and name not in GO_NOT_NEEDED:
            missing.append(name)
        go = ", ".join(f"`{p.removeprefix('go/')}`" for p in found) or GO_NOT_NEEDED.get(name, "**missing**")
        lines.append(f"| `{name}` | {', '.join('`' + p.removeprefix('arkstudio/') + '`' for p in py)} | {go} |")
    return "\n".join(lines) + "\n", missing


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text, missing = render()
    if missing:
        print("not read by the Go server: " + ", ".join(missing), file=sys.stderr)
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{OUT} is stale; run config_parity.py", file=sys.stderr)
            return 1
        return 1 if missing else 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 1 if missing else 0


if __name__ == "__main__":
    raise SystemExit(main())
