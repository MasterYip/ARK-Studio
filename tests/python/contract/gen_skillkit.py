"""Generate the Go copies of the skill templates and CPython's str.upper table.

    python -B tests/python/contract/gen_skillkit.py          # rewrite the generated files
    python -B tests/python/contract/gen_skillkit.py --check  # exit 1 when stale

* go/internal/skillkit/assets_gen.go: the agent-team, rrsi and design template
  texts exactly as ``Path.read_text(encoding="utf-8")`` returns them (universal
  newlines), plus the design ``theme.json`` text.
* go/internal/pytext/upper_gen.go: every code point whose CPython
  ``str.upper()`` differs from itself (full case mappings such as
  ``"ß" -> "SS"`` and ``"ﬀ" -> "FF"``), so ``pytext.Upper`` follows the
  interpreter's Unicode version rather than Go's.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
ASSETS = ROOT / "arkstudio" / "skills" / "assets"
TARGETS = {
    ROOT / "go" / "internal" / "skillkit" / "assets_gen.go": "assets",
    ROOT / "go" / "internal" / "pytext" / "upper_gen.go": "upper",
}
FILES = [
    "agent-team/templates/goal_manifest.md",
    "agent-team/templates/inspection_report.md",
    "agent-team/templates/agent_brief.md",
    "rrsi/proposer.md",
    "rrsi/analyst.md",
    "rrsi/critic.md",
    "design/design_brief.md",
    "design/style_review.md",
    "design/theme.json",
]


def go_string(text: str) -> str:
    # Go rejects a raw BOM inside a source file; JSON and Go share \uXXXX.
    return json.dumps(text, ensure_ascii=False).replace(chr(0xFEFF), "\\" + "ufeff")


def render_assets() -> str:
    lines = ["// Code generated by tests/python/contract/gen_skillkit.py; DO NOT EDIT.", "",
             "package skillkit", "",
             "// assets are arkstudio/skills/assets files as Path.read_text() returns them.",
             "var assets = map[string]string{"]
    for n, name in enumerate(FILES):
        text = (ASSETS / name).read_text(encoding="utf-8")
        lines += ([""] if n else []) + [f"\t{go_string(name)}: {go_string(text)},"]
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_upper() -> str:
    lines = ["// Code generated by tests/python/contract/gen_skillkit.py; DO NOT EDIT.", "",
             "package pytext", "",
             f"// upperTable is CPython {sys.version_info[0]}.{sys.version_info[1]} str.upper() for every code point it changes.",
             "var upperTable = map[rune]string{"]
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        up = ch.upper()
        if up != ch:
            lines.append(f"\t0x{cp:06X}: {go_string(up)},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    stale = False
    for target, kind in TARGETS.items():
        text = render_assets() if kind == "assets" else render_upper()
        if "--check" in argv:
            if not target.is_file() or target.read_text(encoding="utf-8") != text:
                print(f"stale: {target.relative_to(ROOT)}; run python -B tests/python/contract/gen_skillkit.py")
                stale = True
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {target.relative_to(ROOT)}")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
