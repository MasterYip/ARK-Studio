"""Record Python's project seeds as store calls for the Go server.

    python -B tests/python/contract/gen_seeds.py          # rewrite go/internal/project/seeds_gen.go
    python -B tests/python/contract/gen_seeds.py --check  # exit 1 when stale

The blank, paper and demo templates (seed.py) and the tutorial project
(demo._seed) are plain sequences of Store calls.  Each seed runs once against
a scratch store wrapped in a recorder; the recorded calls (method, arguments,
and whether Python raised) are embedded in Go, which replays them through its
own Store port.  Asset files are copied natively by both servers.  Seed text
that depends on files (the tutorial's goal manifest and figure check) is
captured already resolved.
"""
from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
TARGET = ROOT / "go" / "internal" / "project" / "seeds_gen.go"


class Recorder:
    """A Store proxy that records the write calls seeds make."""

    METHODS = {
        "create_unit": ("data", "actor"),
        "create_link": ("source", "target", "relation", "note", "actor"),
        "add_media": ("ref", "url", "kind", "caption", "actor"),
        "design_topic": ("ref", "body", "actor"),
        "update_unit": ("ref", "patch", "actor"),
        "set_meta": ("key", "value"),
    }

    def __init__(self, store):
        self._store = store
        self.ops: list[dict] = []

    def __getattr__(self, name):
        target = getattr(self._store, name)
        if name not in self.METHODS:
            return target
        names = self.METHODS[name]

        def call(*args, **kwargs):
            bound = dict(zip(names, args))
            bound.update(kwargs)
            op = {"op": name, "args": json.loads(json.dumps(bound, ensure_ascii=False))}
            self.ops.append(op)
            try:
                return target(*args, **kwargs)
            except Exception as exc:  # noqa: BLE001 - recorded, re-raised
                op["raises"] = type(exc).__name__
                raise
        return call


def record(seed_fn) -> list[dict]:
    sys.path.insert(0, str(ROOT))
    from arkstudio.store import Store
    with tempfile.TemporaryDirectory(prefix="ark-seed-") as scratch:
        folder = Path(scratch) / "seed.ark"
        for sub in ("assets", "exports", "logs"):
            (folder / sub).mkdir(parents=True, exist_ok=True)
        store = Store(folder, {"id": "seed", "name": "seed"})
        try:
            recorder = Recorder(store)
            seed_fn(recorder, folder)
            return recorder.ops
        finally:
            store.close()


def render() -> str:
    sys.path.insert(0, str(ROOT))
    from arkstudio import demo, seed
    seeds = {
        "blank": record(lambda s, _f: seed.seed_blank(s)),
        "paper": record(lambda s, _f: seed.seed_paper(s)),
        "demo": record(lambda s, f: seed.seed_demo(s, f)),
        "tutorial": record(lambda s, f: demo._seed(s, f)),
    }
    lines = ["// Code generated by tests/python/contract/gen_seeds.py; DO NOT EDIT.", "",
             "package project", "",
             "// seedOps are the Store calls of seed.py / demo._seed, as JSON.",
             "var seedOps = map[string]string{"]
    for n, key in enumerate(sorted(seeds)):
        text = json.dumps(seeds[key], ensure_ascii=False)
        lines += ([""] if n else []) + [f"\t{json.dumps(key)}: {json.dumps(text, ensure_ascii=False)},"]
    lines += ["}", "", "// DemoVersion is demo_content.DEMO_VERSION.",
              f"const DemoVersion = {int(demo.DEMO_VERSION)}", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print(f"stale: {TARGET.relative_to(ROOT)} (run tests/python/contract/gen_seeds.py)")
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
